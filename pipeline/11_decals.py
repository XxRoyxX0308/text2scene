"""FLUX decal images -> export/decals/<id>/ (RGBA base colour + normal + asset.json).

usage: python 11_decals.py <project_dir> [id ...]

Decals (stains, leaks, cracks, dirt, scorch marks, footprints, graffiti) are the cheapest source of close-up
detail and the main tool against visible tiling. Each decal in assets.json "decals" is generated by
01_generate.py like a prop (a top-down photo on pure white) and picked in work/selection.json.

assets.json "decals" entries:
  {"id": "oil_stain", "prompt": "...", "size_m": [1.6, 1.6], "alpha": "luma", "roughness": 0.25}
  alpha "luma"  : dark marks on white -> opacity from darkness (stains, dirt, leaks, cracks, soot)
  alpha "matte" : use work/decals/<id>/rgba.png from 02_select_matte.py (shapes with light colours: paper,
                  paint, signs, leaves)
  optional: "normal_strength" (default 1.5), "opacity" (default 1), "res" (default 1024)
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import textures as tx
from t2s import Project, load, save


def edge_fade(h, w, frac=0.08):
    """1 inside, falling to 0 at the image border so no decal ever shows a square edge."""
    y = np.minimum(np.arange(h), np.arange(h)[::-1]) / (h * frac)
    x = np.minimum(np.arange(w), np.arange(w)[::-1]) / (w * frac)
    return np.clip(np.minimum(y[:, None], x[None, :]), 0, 1) ** 1.5


def from_luma(rgb):
    dark = 1 - tx.luminance(rgb)
    a = np.clip((dark - 0.04) / 0.5, 0, 1) ** 0.8
    color = (rgb - (1 - a[..., None])) / np.maximum(a[..., None], 1e-3)
    return np.clip(color, 0, 1), a


def build(project, only):
    selection = load(project.p("work", "selection.json"), {})
    for d in project.decals():
        if only and d["id"] not in only:
            continue
        work = project.work_decal(d["id"])
        if d["id"] not in selection:
            print(f"{d['id']}: no pick in work/selection.json, skipped")
            continue
        res = int(d.get("res", 1024))
        if d.get("alpha", "luma") == "matte":
            rgba = tx.load(os.path.join(work, "rgba.png"), 4)
            color, a = rgba[..., :3], rgba[..., 3]
        else:
            color, a = from_luma(tx.load(os.path.join(work, f"cand_{selection[d['id']]['pick']}.png")))
        aspect = d.get("size_m", [1, 1])[0] / d.get("size_m", [1, 1])[1]
        w, h = (res, max(64, round(res / aspect))) if aspect >= 1 else (max(64, round(res * aspect)), res)
        a = a * edge_fade(*a.shape) * float(d.get("opacity", 1.0))
        rgba = tx.resize(np.concatenate([color, a[..., None]], axis=2), (w, h))
        normal = tx.normal_from_height(rgba[..., 3], strength=float(d.get("normal_strength", 1.5)))
        out = project.export("decals", d["id"])
        files = tx.write_maps(out, d["id"], rgba, normal, 1.0, float(d.get("roughness", 0.6)), 0.0)
        save(os.path.join(out, "asset.json"), {
            "kind": "decal", "id": d["id"], "size_m": d.get("size_m", [1, 1]),
            "textures": {"bc": files["bc"], "n": files["n"]},
            "params": {"roughness": float(d.get("roughness", 0.6)), "opacity": float(d.get("opacity", 1.0))}})
        print(f"{d['id']}: {w}x{h}, coverage {float((rgba[..., 3] > 0.5).mean()):.2f} -> {out}")


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    build(Project(sys.argv[1]), set(sys.argv[2:]))
